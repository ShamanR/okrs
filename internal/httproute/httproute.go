// Package httproute отвечает на один вопрос: как назвать запрошенный ресурс так,
// чтобы это можно было писать в лог.
//
// Пакет-лист: зависит только от net/http и роутера. Живёт отдельно от
// internal/http/middleware, потому что им пользуется и internal/auth, а
// middleware импортирует auth — общий помощник в middleware дал бы цикл.
//
// Одно место на всё приложение выбрано намеренно: правило «в лог идёт шаблон, а
// не путь» относится к безопасности, и разъехавшиеся копии уже приводили к утечке —
// шаблон появился в записи о запросе, но не в записи о панике.
package httproute

import (
	"net/http"

	"github.com/go-chi/chi/v5"
)

// Pattern возвращает шаблон совпавшего маршрута вида /invite/{token}.
//
// Шаблон, а не конкретный путь, потому что значение параметра маршрута может быть
// учётными данными: токен приглашения в /invite/{token} остаётся действующим, и
// любой, у кого есть доступ к логам, принял бы чужое приглашение. Редакция по имени
// ключа произвольную строку под ключом path не маскирует.
//
// Шаблон известен не везде: chi заполняет свой RouteContext по ходу маршрутизации,
// поэтому во внешнем middleware до вызова next его ещё нет, а в обработчике,
// после next и в middleware вложенной группы — уже есть.
//
// Когда шаблона нет (несовпавший путь, ранний middleware), возвращается
// запрошенный путь: без него не видно, что именно отдаёт 404 после выката, а
// несовпавший путь по определению не принадлежит ни одному маршруту приложения.
//
// TODO: заменить откат на конкретный путь устойчивым псевдонимом. Секрет может
// оказаться в пути и там, где маршрут не совпал: опечатка в токене приглашения
// даёт 404, и действующая часть учётных данных всё равно уходит в лог. Решается
// отдельным proposal — нужно выбрать псевдоним, сохраняющий диагностическую
// ценность записи о 404.
func Pattern(r *http.Request) string {
	if rctx := chi.RouteContext(r.Context()); rctx != nil {
		if p := rctx.RoutePattern(); p != "" {
			return p
		}
	}
	return r.URL.Path
}
