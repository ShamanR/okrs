-- Возвращает прежнее представление: до наката у числового KR current_value
-- всегда было заполнено, а у необновлённого равнялось стартовому значению.
-- Переписываются и строки, созданные уже после наката, — это и есть прежнее
-- поведение, а не потеря данных: пустое текущее значение и означало «равно
-- стартовому». Идемпотентно.
UPDATE key_results
SET current_value = start_value
WHERE kind = 'NUMERICAL'
  AND current_value IS NULL
  AND start_value IS NOT NULL;
