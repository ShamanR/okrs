-- Текущее значение числового KR перестаёт быть частью его определения: пока
-- прогресс ни разу не обновляли, current_value пустое, а чтение отдаёт
-- start_value. Существующие строки приводятся к тому же виду.
--
-- Предикат подобран так, что ни одно читаемое значение не меняется:
--   * progress_updated_at IS NULL — прогресс ни разу не обновляли;
--   * current_value = start_value — страховка от строк, прогресс которых
--     обновляли ещё до появления progress_updated_at: у них момент обновления
--     пустой, но текущее значение настоящее и трогать его нельзя.
-- Раз значения равны, после обнуления чтение вернёт то же число — прогресс и
-- health-статус остаются прежними. Меняется только то, что последующая правка
-- стартового значения потянет за собой текущее. Идемпотентно.
UPDATE key_results
SET current_value = NULL
WHERE kind = 'NUMERICAL'
  AND progress_updated_at IS NULL
  AND current_value IS NOT NULL
  AND start_value IS NOT NULL
  AND current_value = start_value;
