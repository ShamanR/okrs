-- Текущее значение числового KR перестаёт быть частью его определения: пока
-- прогресс ни разу не обновляли, current_value пустое, а чтение отдаёт
-- start_value. Существующие строки приводятся к тому же виду.
--
-- Опасность здесь одна: строка, прогресс которой обновляли ещё до того, как
-- миграция 012 добавила progress_updated_at. У неё момент обновления пустой, а
-- текущее значение настоящее, и обнулять его нельзя. Отличить такую строку от
-- никогда не обновлявшейся по значениям невозможно: если тот давний чек-ин
-- пришёлся ровно на стартовое значение, обе выглядят одинаково. Журнал
-- активностей здесь тоже не помощник — он появился только в миграции 039.
--
-- Поэтому строка обнуляется лишь тогда, когда её безопасность доказуема:
--   * progress_updated_at IS NULL — прогресс не обновляли ПОСЛЕ миграции 012;
--   * current_value = start_value — значение не отличается от стартового, то
--     есть чтение после обнуления вернёт то же число;
--   * created_at позже самого раннего известного момента обновления прогресса —
--     значит на момент создания строки колонка progress_updated_at уже
--     существовала, и любой чек-ин по этой строке её бы проштамповал. Пустой
--     штамп у такой строки означает именно «не обновляли ни разу».
-- Самые первые строки базы, созданные раньше первого в её истории чек-ина, не
-- трогаются: про них доказать нечего, и они сохраняют прежнее поведение. Если
-- штампов нет вовсе, подзапрос даёт NULL и миграция не меняет ни одной строки.
--
-- Ни одно читаемое значение, ни один процент прогресса и ни один health-статус
-- при этом не меняются: обнуляются только строки, где значение равно стартовому.
-- Меняется лишь то, что последующая правка старта потянет за собой текущее
-- значение. Идемпотентно.
UPDATE key_results
SET current_value = NULL
WHERE kind = 'NUMERICAL'
  AND progress_updated_at IS NULL
  AND current_value IS NOT NULL
  AND start_value IS NOT NULL
  AND current_value = start_value
  AND created_at > (
      SELECT MIN(progress_updated_at) FROM key_results WHERE progress_updated_at IS NOT NULL
  );
